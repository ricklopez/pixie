"""Origin, effect and input-binding policy enforced in code around every engine decision."""

import re
from urllib.parse import urlsplit

EFFECT_OF_KIND = {"click": "click", "fill": "type", "select": "select"}
ALWAYS_ALLOWED_KINDS = {"wait", "scroll"}


class PolicyRejection(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


def _norm(text):
    return re.sub(r"\s+", " ", (text or "")).strip().casefold()


def origin_of(url):
    parts = urlsplit(url)
    if not parts.scheme or not parts.netloc:
        return None
    return f"{parts.scheme}://{parts.netloc}"


def check_origin(url, allowed_origins):
    origin = origin_of(url)
    if origin is None or origin not in allowed_origins:
        raise PolicyRejection("origin", f"Page origin {origin!r} is outside the allowed origins")


def bound_input(checkpoint, definition, action):
    """The reviewed input whose confirmed target label matches this observed field, or None."""
    label = _norm(action.get("label", ""))
    for field in definition["inputs"]:
        binding = field["binding"]
        if binding["checkpointId"] != checkpoint["id"]:
            continue
        wanted = _norm(binding["targetLabel"])
        if wanted and (wanted == label or wanted in label):
            return field
    return None


def check_action(checkpoint, definition, action):
    """Raise PolicyRejection unless the observed action is allowed by the reviewed checkpoint."""
    kind = action.get("kind")
    if kind in ALWAYS_ALLOWED_KINDS:
        return None
    effect = EFFECT_OF_KIND.get(kind)
    if effect is None:
        raise PolicyRejection("unsupported", f"Action kind {kind!r} is not supported")
    if effect not in checkpoint["allowedEffects"]:
        raise PolicyRejection("effect", f"Effect {effect!r} is not allowed in checkpoint {checkpoint['id']!r}")
    if kind == "fill":
        field = bound_input(checkpoint, definition, action)
        if field is None:
            raise PolicyRejection(
                "unbound-field",
                f"No reviewed input is bound to field {action.get('label')!r}; text is never generated by a model here",
            )
        return field
    return None
