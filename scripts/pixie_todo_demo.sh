#!/usr/bin/env bash
# Pixie Todo demo: publishes the four reviewed Todo operations (create/list/update/delete) against
# https://todo.uiineed.com/ through the Studio API, then invokes them as a separate API client.
#
# Prerequisites: the API is running (npm run dev:api or node apps/api/dist/main.js) with GATEWAY_ENGINE=live
# and TYPESAFE_API_KEY set (or GATEWAY_ENGINE=scripted for the offline, no-model variant).
#
# Usage: scripts/pixie_todo_demo.sh [publish|crud|all|isolation-before|isolation-after] [title-suffix]
#   isolation-before <suffix>: creates a task in account $PIXIE_ACCOUNT, then asks you to stop and restart the API
#   isolation-after  <suffix>: lists from the restarted browser of $PIXIE_ACCOUNT (task must persist), lists from a
#                              second account $PIXIE_ACCOUNT_B (task must be absent), then deletes the task.
set -euo pipefail

API=${GATEWAY_URL:-http://127.0.0.1:4180}
DEV=${GATEWAY_DEV_TOKEN:-dev-token-local}
CLIENT=${GATEWAY_CLIENT_TOKEN:-client-token-local}
ACCOUNT=${PIXIE_ACCOUNT:-acct_todo}
ACCOUNT_B=${PIXIE_ACCOUNT_B:-acct_todo_b}
ORIGIN=https://todo.uiineed.com
MODE=${1:-all}
SUFFIX=${2:-$(date +%H%M%S)}
STATE_FILE=${PIXIE_STATE_FILE:-artifacts/pixie-todo-demo.env}

# curl fails (exit 22) on any non-2xx status so a rejected request can never be mistaken for success.
dev() { curl -sSf -H "Authorization: Bearer $DEV" -H "Content-Type: application/json" "$@"; }
client() { curl -sSf -H "Authorization: Bearer $CLIENT" -H "Content-Type: application/json" "$@"; }
jqr() { python3 -c "import json,sys; d=json.load(sys.stdin); d=d.get('run',d) if isinstance(d,dict) and 'run' in d else d; print(eval('d'+sys.argv[1]))" "$1"; }

wait_run() { # wait_run <url of run status>
  local url=$1 state
  for _ in $(seq 1 120); do
    state=$(curl -sSf -H "Authorization: Bearer $2" "$url" | jqr "['state']")
    case "$state" in completed|needs_review|failed|awaiting_auth|cancelled) echo "$state"; return;; esac
    sleep 1
  done
  echo timeout
}

publish_all() {
  mkdir -p "$(dirname "$STATE_FILE")"
  echo "# generated by scripts/pixie_todo_demo.sh" > "$STATE_FILE"
  dev -X POST "$API/studio/accounts" -d "{\"id\":\"$ACCOUNT\",\"name\":\"Pixie Todo demo profile\",\"portalOrigin\":\"$ORIGIN\"}" >/dev/null || true
  for template in create-todo list-todos update-todo delete-todo; do
    echo "== publishing $template"
    id=$(dev -X POST "$API/studio/automations" -d "{\"name\":\"$template\",\"startUrl\":\"$ORIGIN/\",\"template\":\"$template\"}" | jqr "['id']")
    definition=$(dev "$API/studio/automations/$id" | python3 -c "import json,sys; print(json.dumps(json.load(sys.stdin)['definition']))")
    dev -X PUT "$API/studio/automations/$id/definition" -d "$definition" >/dev/null
    case $template in
      create-todo) input="{\"title\":\"pixie-demo publish-check $SUFFIX\"}";;
      list-todos) input="{}";;
      update-todo) input="{\"title\":\"pixie-demo publish-check $SUFFIX\",\"newTitle\":\"pixie-demo publish-check $SUFFIX (renamed)\"}";;
      delete-todo) input="{\"title\":\"pixie-demo publish-check $SUFFIX (renamed)\"}";;
    esac
    run=$(dev -X POST "$API/studio/automations/$id/test" -d "{\"accountId\":\"$ACCOUNT\",\"input\":$input}" | jqr "['id']")
    state=$(wait_run "$API/studio/runs/$run" "$DEV")
    echo "   test run $run -> $state"
    if [ "$state" != completed ]; then dev "$API/studio/runs/$run" | jqr ".get('failure')"; exit 1; fi
    revision=$(dev -X POST "$API/studio/automations/$id/publish" -d '{}' | jqr "['revision']")
    [ "$revision" = 1 ] || { echo "publish of $template did not return revision 1 (got '$revision')"; exit 1; }
    echo "   published $id revision $revision"
    echo "PIXIE_$(echo "$template" | tr 'a-z-' 'A-Z_')=$id" >> "$STATE_FILE"
  done
  echo "published ids written to $STATE_FILE"
}

invoke() { # invoke <automation id> <input json> [account id]
  local id=$1 input=$2 account=${3:-$ACCOUNT} run state
  run=$(client -X POST "$API/v1/automations/$id/runs" -H "Idempotency-Key: $(uuidgen 2>/dev/null || date +%s%N)" -d "{\"revision\":1,\"accountId\":\"$account\",\"input\":$input}" | jqr "['id']")
  state=$(wait_run "$API/v1/automations/$id/runs/$run" "$CLIENT")
  echo "   run $run -> $state"
  # /result is 200 only for an accepted result; otherwise 409 with the run view (state + failure).
  curl -sS -H "Authorization: Bearer $CLIENT" "$API/v1/automations/$id/runs/$run/result" | python3 -c "
import json,sys; r=json.load(sys.stdin)
if r.get('accepted'):
    tasks=(r.get('data') or {}).get('tasks')
    print('   accepted: checks', sum(1 for c in r['checks'] if c.get('passed')), '/', len(r['checks']), 'ok')
    if tasks is not None: print('   tasks:', [t['text'] for t in tasks])
else:
    print('   not accepted:', r.get('state'), '|', r.get('failure') or r.get('error'))"
  [ "$state" = completed ]
}

crud() {
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  T="pixie-demo groceries $SUFFIX"
  echo "== create-todo  title=$T";            invoke "$PIXIE_CREATE_TODO" "{\"title\":\"$T\"}"
  echo "== list-todos";                        invoke "$PIXIE_LIST_TODOS" "{}"
  echo "== safety: duplicate create (expected needs_review, no change)"; invoke "$PIXIE_CREATE_TODO" "{\"title\":\"$T\"}" || true
  echo "== update-todo  -> '$T (done)'";       invoke "$PIXIE_UPDATE_TODO" "{\"title\":\"$T\",\"newTitle\":\"$T (done)\"}"
  echo "== delete-todo  '$T (done)'";          invoke "$PIXIE_DELETE_TODO" "{\"title\":\"$T (done)\"}"
  echo "== list-todos (after)";                invoke "$PIXIE_LIST_TODOS" "{}"
  echo "== safety: delete nonexistent (expected needs_review)";        invoke "$PIXIE_DELETE_TODO" "{\"title\":\"pixie-demo does-not-exist\"}" || true
  echo "== safety: delete outside prefix (expected needs_review)";     invoke "$PIXIE_DELETE_TODO" "{\"title\":\"someone elses task\"}" || true
}

isolation_before() {
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  T="pixie-demo p7 $SUFFIX"
  echo "== [$ACCOUNT] create-todo title=$T"; invoke "$PIXIE_CREATE_TODO" "{\"title\":\"$T\"}"
  echo "== [$ACCOUNT] list-todos";           invoke "$PIXIE_LIST_TODOS" "{}"
  echo
  echo "Now stop the API gracefully (Ctrl-C / SIGINT closes every account browser), start it again, then run:"
  echo "  $0 isolation-after $SUFFIX"
}

isolation_after() {
  # shellcheck disable=SC1090
  source "$STATE_FILE"
  T="pixie-demo p7 $SUFFIX"
  dev -X POST "$API/studio/accounts" -d "{\"id\":\"$ACCOUNT_B\",\"name\":\"Pixie second account (isolation check)\",\"portalOrigin\":\"$ORIGIN\"}" >/dev/null 2>&1 || true
  echo "== [$ACCOUNT] list-todos after restart (expect '$T' present)"; invoke "$PIXIE_LIST_TODOS" "{}" | tee /tmp/pixie-p7-a.txt
  grep -q "$T" /tmp/pixie-p7-a.txt || { echo "FAIL: task did not survive the restart"; exit 1; }
  echo "== [$ACCOUNT_B] list-todos (expect '$T' absent)";           invoke "$PIXIE_LIST_TODOS" "{}" "$ACCOUNT_B" | tee /tmp/pixie-p7-b.txt
  grep -q "$T" /tmp/pixie-p7-b.txt && { echo "FAIL: second account can see the first account's task"; exit 1; }
  echo "== [$ACCOUNT_B] delete-todo '$T' (expect needs_review: not present in this account)"; invoke "$PIXIE_DELETE_TODO" "{\"title\":\"$T\"}" "$ACCOUNT_B" || true
  echo "== [$ACCOUNT] delete-todo '$T' (cleanup)";                   invoke "$PIXIE_DELETE_TODO" "{\"title\":\"$T\"}"
  echo "== browser profiles known to the API"; dev "$API/studio/accounts" | python3 -c "import json,sys; [print('  ', a['id'], a['browser']) for a in json.load(sys.stdin)]"
  echo "P7 isolation check passed"
}

case $MODE in
  publish) publish_all;;
  crud) crud;;
  all) publish_all; crud;;
  isolation-before) isolation_before;;
  isolation-after) isolation_after;;
  *) echo "usage: $0 [publish|crud|all] [suffix]"; exit 2;;
esac
